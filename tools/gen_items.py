# items.tsv (shroudlink categories: item id -> debug name, current build) -> C++ table
import sys
src, out = sys.argv[1], sys.argv[2]
rows = []
for line in open(src, encoding='utf-8'):
    parts = line.rstrip('\n').split('\t')
    if len(parts) >= 2 and parts[0].isdigit() and parts[1]:
        rows.append((int(parts[0]), parts[1]))
rows.sort(key=lambda r: r[1])
with open(out, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/gen_items.py from shroudlink mod/categories/items.tsv (MIT):\n')
    f.write('// the game\'s item ids by debug name, sorted by name.\n#pragma once\n#include <cstdint>\n\n')
    f.write('struct ItemName { const char* name; uint32_t id; };\n')
    f.write(f'inline constexpr ItemName kItems[] = {{\n')
    for i, n in rows:
        f.write(f'    {{"{n}", {i}u}},\n')
    f.write('};\n')
print(len(rows))
